// Build: validate data → generate src/generated/data.ts → tsc → assemble a static site in dist/.
// No bundler and no runtime dependencies: the output is plain ES modules plus the vendored
// Brilliant Web Skill tokens, CSS and JS. Works on any static host (GitHub Pages included).
import { readFileSync, writeFileSync, mkdirSync, cpSync, rmSync, existsSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { loadData, validate } from './validate-data.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dist = join(root, 'dist');

const data = loadData();
const errors = validate(data);
if (errors.length) { console.error('Data validation failed:\n' + errors.join('\n')); process.exit(1); }

mkdirSync(join(root, 'src/generated'), { recursive: true });
writeFileSync(join(root, 'src/generated/data.ts'),
  `// Generated by scripts/build.mjs from /data/*.json. Do not edit by hand.\nimport type { AppData } from '../types.js';\nexport const DATA: AppData = ${JSON.stringify(data, null, 1)};\n`);

rmSync(dist, { recursive: true, force: true });
const localTsc = join(root, 'node_modules/.bin/tsc');
execSync(`${existsSync(localTsc) ? localTsc : 'tsc'} -p tsconfig.json`, { cwd: root, stdio: 'inherit' });

cpSync(join(root, 'vendor/brilliant'), join(dist, 'vendor/brilliant'), { recursive: true });
cpSync(join(root, 'src/styles'), join(dist, 'styles'), { recursive: true });
const sprite = readFileSync(join(root, 'vendor/brilliant/assets/icons.svg'), 'utf8').replace(/<\?xml[^>]*>/, '');
const appSprite = readFileSync(join(root, 'src/icons.svg'), 'utf8');
const html = readFileSync(join(root, 'src/index.html'), 'utf8')
  .replace('<!--ICONS-->', sprite.replace('<svg', '<svg aria-hidden="true" style="display:none"') + appSprite)
  .replaceAll('__VERIFIED__', data.verifiedDate);
writeFileSync(join(dist, 'index.html'), html);
writeFileSync(join(dist, '.nojekyll'), '');
writeFileSync(join(dist, 'sources.json'), readFileSync(join(root, 'data/sources.json')));
console.log('built dist/');
